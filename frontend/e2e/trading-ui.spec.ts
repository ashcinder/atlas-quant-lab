import { test, expect, login, route, fixture } from './helpers'

test('RUNTIME-03 two actual UI instances pause resume inspect and stop independently', async ({ page }) => {
  test.setTimeout(90_000)
  await login(page, 'author')
  await route(page, '#/trading')
  const ids: string[] = []
  for (let index = 0; index < 2; index++) {
    await page.getByRole('button', { name: '新建运行', exact: true }).first().click()
    const dialog = page.getByRole('dialog', { name: '新建策略运行' })
    await dialog.getByRole('combobox', { name: '策略版本', exact: true }).selectOption(fixture().releases.public)
    const created = page.waitForResponse(response => response.url().endsWith('/trading/runs') && response.request().method() === 'POST')
    await dialog.getByRole('button', { name: '启动模拟', exact: true }).click()
    const response = await created
    expect(response.ok()).toBe(true)
    ids.push((await response.json()).id)
    await expect(dialog).toBeHidden()
  }
  for (const id of ids) {
    const card = page.locator('article[id=' + JSON.stringify(id) + ']')
    await card.getByRole('button', { name: '运行详情', exact: true }).click()
    await expect(card).toContainText('运行中')
    await card.getByRole('button', { name: '暂停', exact: true }).click()
    await expect(card).toContainText('已暂停')
    expect((await (await page.request.get('/api/v1/trading/runs/' + id)).json()).status).toBe('paused')
    await card.getByRole('button', { name: '恢复', exact: true }).click()
    await expect(card).toContainText('运行中')
    const ticked = page.waitForResponse(response => response.url().endsWith('/compute/runtime/' + id + '/signal'))
    await card.getByRole('button', { name: '立即检查', exact: true }).click()
    expect((await ticked).ok()).toBe(true)
    await card.getByRole('button', { name: '停止', exact: true }).click()
    await expect(card).toContainText('已停止')
    await expect(card.getByRole('button', { name: '立即检查', exact: true })).toBeDisabled()
  }
  await page.reload()
  for (const id of ids) expect((await (await page.request.get('/api/v1/trading/runs/' + id)).json()).status).toBe('stopped')
})

for (const venue of ['binance', 'okx']) {
  test('TRADE-03-' + venue + ' user configures a demo venue and queries cancels through the actual interface', async ({ page, account }) => {
    await login(page, account)
    await route(page, '#/trading')
    await page.getByRole('button', { name: '接入模拟账户', exact: true }).click()
    const dialog = page.getByRole('dialog')
    await dialog.getByRole('combobox', { name: '模拟交易所', exact: true }).selectOption(venue)
    await dialog.getByLabel('模拟 API Key', { exact: true }).fill('synthetic-matrix-' + account)
    await dialog.getByLabel('模拟 API Secret', { exact: true }).fill('synthetic-isolated-secret')
    if (venue === 'okx') await dialog.getByLabel('模拟 Passphrase', { exact: true }).fill('synthetic-passphrase')
    await dialog.getByRole('checkbox').check()
    await dialog.getByRole('button', { name: '验证连接并保存', exact: true }).click()
    await expect(dialog).toContainText('模拟账户已验证并保存')
    await page.getByRole('button', { name: '关闭操作面板' }).click()
    await page.getByRole('button', { name: '人工下单', exact: true }).click()
    await dialog.getByRole('button', { name: venue === 'binance' ? '币安 Binance' : '欧易 OKX', exact: true }).click()
    await dialog.getByLabel('交易对', { exact: true }).fill('BTC-USDT')
    await dialog.getByLabel('数量（基础币）', { exact: true }).fill('0.001')
    await dialog.getByLabel('限价（USDT）', { exact: true }).fill('10000')
    const previewed = page.waitForResponse(response => response.url().endsWith('/orders/preview'))
    await dialog.getByRole('button', { name: '预览订单', exact: true }).click()
    const preview = await (await previewed).json()
    await dialog.getByLabel('确认文字', { exact: true }).fill('确认模拟下单')
    await dialog.getByRole('button', { name: '确认提交订单', exact: true }).click()
    await expect(dialog).toBeHidden()
    const row = page.locator('#order-' + preview.id)
    const refreshed = page.waitForResponse(response => response.url().endsWith('/orders/' + preview.id + '/refresh'))
    await row.getByRole('button', { name: '查询状态', exact: true }).click()
    expect((await refreshed).ok()).toBe(true)
    page.once('dialog', confirmation => confirmation.dismiss())
    await row.getByRole('button', { name: '撤单', exact: true }).click()
    await expect(row.getByRole('button', { name: '撤单', exact: true })).toBeEnabled()
    const cancelled = page.waitForResponse(response => response.url().endsWith('/orders/' + preview.id + '/cancel'))
    page.once('dialog', confirmation => confirmation.accept())
    await row.getByRole('button', { name: '撤单', exact: true }).click()
    const reply = await cancelled
    expect(reply.ok()).toBe(true)
    expect((await reply.json()).result.exchange_status.toUpperCase()).toBe('CANCELED')
    await expect(row.getByRole('button', { name: '撤单', exact: true })).toBeDisabled()
    await page.reload()
    const orders = await (await page.request.get('/api/v1/trading/orders')).json()
    expect(orders.filter((order: { id: string }) => order.id === preview.id)).toHaveLength(1)
  })
}
