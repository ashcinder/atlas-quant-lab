async function ledger(page: import('@playwright/test').Page) {
  return (await (await page.request.get('/api/ledger')).json()).state
}

async function createAccount(page: import('@playwright/test').Page, name: string) {
  await route(page, '#/journal/accounts')
  await page.getByRole('button', { name: '新增账户', exact: true }).click()
  const dialog = page.getByRole('dialog')
  await dialog.getByLabel('账户名称', { exact: true }).fill(name)
  await dialog.getByRole('button', { name: '保存账户', exact: true }).click()
  await expect(dialog).toBeHidden()
  return (await ledger(page)).accounts.find((account: { name: string }) => account.name === name)
}

